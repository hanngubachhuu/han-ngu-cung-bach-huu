export function cbtText(text, language) {
  if (language !== "zh") return text;
  if (chinese[text]) return chinese[text];
  const patterns = [
    [
      /^(\d+) \/ (\d+) câu đã lưu$/,
      (_, n, total) => `已保存 ${n} / ${total} 题`,
    ],
    [
      /^Đã lưu (\d+)\/(\d+) câu\.$/,
      (_, n, total) => `已保存 ${n}/${total} 题。`,
    ],
    [/^(\d+) câu · (\d+) phần$/, (_, n, parts) => `${n} 题 · ${parts} 部分`],
    [/^PHẦN (\d+)$/, (_, n) => `第${n}部分`],
    [
      /^Câu (\d+)–(\d+) · (\d+) câu$/,
      (_, first, last, n) => `第${first}–${last}题 · 共${n}题`,
    ],
    [
      /^(\d+) giây trả lời mỗi câu( · ([\d:]+) chuẩn bị)?$/,
      (_, n, more, prep) =>
        `每题答题时间 ${n} 秒${more ? ` · 准备时间 ${prep}` : ""}`,
    ],
    [/^Câu (\d+)\.$/, (_, n) => `第${n}题。`],
    [
      /^Đã hoàn thành câu (\d+)\. Chuyển sang câu (\d+)\.$/,
      (_, previous, next) => `第${previous}题结束。进入第${next}题。`,
    ],
    [/^Tranh câu (\d+)$/, (_, n) => `第${n}题图片`],
    [
      /^Audio câu (\d+) chưa phát đầy đủ\. Lượt thi này cần được kiểm tra lại\.$/,
      (_, n) => `第${n}题音频未完整播放。此场考试需要检查。`,
    ],
    [
      /^Đã hết thời hạn tải bản ghi\. Server đã lưu (\d+)\/(\d+) câu; bài chưa được nộp\. Giữ cửa sổ này để bảo toàn các bản ghi còn lại\.$/,
      (_, n, total) =>
        `录音上传期限已过。服务器已保存 ${n}/${total} 题，尚未交卷。请保留此窗口，以保留剩余录音。`,
    ],
    [
      /^Đã hết thời hạn tải bản ghi\. Đã lưu (\d+)\/(\d+) câu; bài chưa được nộp\.$/,
      (_, n, total) => `录音上传期限已过。已保存 ${n}/${total} 题，尚未交卷。`,
    ],
    [
      /^Chưa nộp được bài\. Đã lưu (\d+)\/(\d+) câu; giữ trang mở và thử lưu lại khi kết nối ổn định\.$/,
      (_, n, total) =>
        `交卷未完成。已保存 ${n}/${total} 题；请保持页面打开，网络稳定后重试保存。`,
    ],
  ];
  for (const [pattern, replacement] of patterns)
    if (pattern.test(text)) return text.replace(pattern, replacement);
  return text;
}
export function localizeCBT(root, language) {
  if (language !== "zh") return;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  let node;
  while ((node = walker.nextNode()))
    node.textContent = cbtText(node.textContent, language);
  root.querySelectorAll("[aria-label], [alt]").forEach((element) => {
    for (const attribute of ["aria-label", "alt"])
      if (element.hasAttribute(attribute))
        element.setAttribute(
          attribute,
          cbtText(element.getAttribute(attribute), language),
        );
  });
}
